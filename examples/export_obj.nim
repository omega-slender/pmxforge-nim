## Wavefront OBJ export.
##
## Converts a PMX model into an OBJ file and a matching MTL file, splitting the geometry by material range.

import std/[strformat, strutils]
import pmxforge

proc plural(count: int, singular, many: string): string =
  ## Returns "1 material" or "3 materials", so the report reads like English.
  if count == 1: fmt"{count} {singular}" else: fmt"{count} {many}"

proc materialName*(index: int, material: Material): string =
  ## Returns a material identifier that a wavefront parser reads back without guessing.
  ## The item index is part of the name because two PMX materials may share a name, and
  ## sanitizing whitespace can merge distinct ones ('a b' and 'a_b'); OBJ and MTL both
  ## use this function, so the assignment stays unambiguous.
  let base =
    if material.nameEN.len > 0:
      material.nameEN
    elif material.nameJA.len > 0:
      material.nameJA
    else:
      "material"
  result = fmt"material_{index}_"
  for character in base:
    result.add (if character in {' ', '\t', '\n', '\r'}: '_' else: character)

proc faceLine(face: Face): string =
  ## Returns one OBJ face line, repeating the index for position, UV, and normal.
  result = "f"
  for corner in face.getIndices():
    let position = int(corner) + 1
    result.add fmt" {position}/{position}/{position}"

proc mtlTexturePath*(path: string): string =
  ## Returns a path that cannot inject extra MTL statements. Newlines, carriage
  ## returns, and other ASCII controls are dropped; the rest is kept as stored.
  for character in path:
    if character.ord >= 32 and character != '\x7f':
      result.add character

proc writeMtl*(model: PmxModel, path: string) =
  ## Writes one material per PMX material, with its colors and diffuse map.
  var lines: seq[string] = @["# Generated by PMX Forge."]
  for index, material in model.materials:
    lines.add ""
    lines.add fmt"newmtl {materialName(index, material)}"
    lines.add fmt"Kd {material.diffuseColor.r:.6f} " &
      fmt"{material.diffuseColor.g:.6f} {material.diffuseColor.b:.6f}"
    lines.add fmt"Ka {material.ambientColor.r:.6f} " &
      fmt"{material.ambientColor.g:.6f} {material.ambientColor.b:.6f}"
    lines.add fmt"Ks {material.specularColor.r:.6f} " &
      fmt"{material.specularColor.g:.6f} {material.specularColor.b:.6f}"
    lines.add fmt"Ns {material.specularStrength:.6f}"
    lines.add fmt"d {material.alpha:.6f}"
    if material.textureIndex >= 0 and material.textureIndex < model.textures.len:
      lines.add fmt"map_Kd {mtlTexturePath(model.textures[material.textureIndex].path)}"
  writeFile(path, lines.join("\n") & "\n")

proc writeObj*(model: PmxModel, path, mtlFile: string): tuple[written, unmatched: int] =
  ## Writes positions, UVs, normals, and the per-material face ranges.
  var lines: seq[string] = @[]
  lines.add "# Exported by PMX Forge."
  lines.add fmt"# {model.vertices.len} vertices, {model.faces.len} triangles."
  if not model.isValid():
    lines.add "# Warning: this model does not pass validation."
  lines.add fmt"mtllib {mtlFile}"
  for vertex in model.vertices:
    lines.add fmt"v {vertex.position.x:.6f} " & fmt"{vertex.position.y:.6f} {vertex.position.z:.6f}"
  for vertex in model.vertices:
    lines.add fmt"vt {vertex.uv.x:.6f} {1.0'f32 - vertex.uv.y:.6f}"
  for vertex in model.vertices:
    lines.add fmt"vn {vertex.normal.x:.6f} " & fmt"{vertex.normal.y:.6f} {vertex.normal.z:.6f}"

  var cursor = 0
  for index, material in model.materials:
    if material.faceCount <= 0:
      continue
    lines.add fmt"usemtl {materialName(index, material)}"
    let last = min(cursor + int(material.faceCount), model.faces.len)
    while cursor < last:
      lines.add faceLine(model.faces[cursor])
      inc cursor
  result.written = cursor

  result.unmatched = model.faces.len - cursor
  if result.unmatched > 0:
    lines.add "# Triangles that no material claims."
    while cursor < model.faces.len:
      lines.add faceLine(model.faces[cursor])
      inc cursor
  writeFile(path, lines.join("\n") & "\n")

when isMainModule:
  import std/os

  if paramCount() < 1:
    quit(
      "usage: export_obj <model.pmx> [model.obj]\n" &
        "Generate a sample first: nim c -r examples/make_sample.nim",
      1)
  let input = paramStr(1)
  if not fileExists(input):
    quit(fmt"No such file: {input}", 1)
  let output =
    if paramCount() >= 2:
      paramStr(2)
    else:
      changeFileExt(input, "obj")
  let mtlFile = changeFileExt(extractFilename(output), "mtl")
  let mtlPath = parentDir(output) / mtlFile

  let model = readPmx(input, DesktopPmxReadLimits)
  let summary = writeObj(model, output, mtlFile)
  writeMtl(model, mtlPath)

  echo &"wrote {output} with {plural(summary.written, \"triangle\", \"triangles\")}"
  echo &"wrote {mtlPath} with {plural(model.materials.len, \"material\", \"materials\")}"
  if summary.unmatched > 0:
    echo &"{plural(summary.unmatched, \"triangle\", \"triangles\")} " &
      fmt"outside every material range"
  if not model.isValid():
    echo "The model does not pass validation, so check the export before using it."
