## Sample model generator.
##
## Builds a rigged cloth plane and writes it to disk, so the other examples have a real PMX file to open.

import std/strformat
import pmxforge

when isMainModule:
  import std/os

const
  Columns = 4 ## Cells along the X axis.
  Rows = 4 ## Cells along the Y axis.
  Bones = 4 ## Bones in the flat spine chain.
  TopRow = Rows ## Row that carries the PMX 2.1 skinning.

proc boneAt(height: float32): tuple[first, second: int32, weight: float32] =
  ## Returns the two bones that share a vertex at this height.
  let scaled = height * float32(Bones - 1)
  let first = min(int(scaled), Bones - 2)
  result = (first: int32(first), second: int32(first + 1), weight: 1.0'f32 - (scaled - float32(first)))

proc makeVertices(): seq[Vertex] =
  ## Builds the grid, with one skinning style per row so the tools have variety.
  for row in 0 .. Rows:
    for column in 0 .. Columns:
      let x = float32(column) / float32(Columns) - 0.5'f32
      let y = float32(row) / float32(Rows)
      let position = Vector3(x: x, y: y, z: 0.0'f32)
      let skinning =
        if row == TopRow:
          newQDEF(0'i32, 1'i32, 2'i32, 3'i32, 0.4'f32, 0.3'f32, 0.2'f32, 0.1'f32)
        elif row == 0:
          newBDEF1(0'i32)
        elif row == 2 and column == 0:
          let blend = boneAt(y)
          newSDEF(blend.first, blend.second, blend.weight, c = position)
        else:
          let blend = boneAt(y)
          newBDEF2(blend.first, blend.second, blend.weight)
      result.add newVertex(
        position = position,
        normal = Vector3.forward,
        uv = Vector2(x: float32(column) / float32(Columns), y: y),
        weightDeform = skinning
      )

proc makeFaces(): seq[Face] =
  ## Builds two triangles per cell, wound to match the +Z normal.
  for row in 0 ..< Rows:
    for column in 0 ..< Columns:
      let bottomLeft = int32(row * (Columns + 1) + column)
      let topLeft = bottomLeft + int32(Columns + 1)
      result.add newFace(bottomLeft, bottomLeft + 1, topLeft + 1)
      result.add newFace(bottomLeft, topLeft + 1, topLeft)

proc makeBones(): seq[Bone] =
  ## Builds a flat spine where every bone follows the one below it.
  for index in 0 ..< Bones:
    result.add newBone(
      nameJA = fmt"bone{index}",
      nameEN = "",
      position = Vector3(x: 0.0'f32, y: float32(index) / float32(Bones - 1), z: 0.0'f32),
      parentBoneIndex = (if index == 0: -1'i32 else: int32(index - 1))
    )

proc makeMorphs(): seq[Morph] =
  ## Pushes the middle row forward and wraps that morph in two others.
  var wave: seq[MorphOffset] = @[]
  for column in 0 .. Columns:
    wave.add MorphOffset(
      kind: moVertex,
      vertex: VertexMorphOffset(
        vertexIndex: int32(2 * (Columns + 1) + column),
        translation: Vector3(x: 0.0'f32, y: 0.0'f32, z: 0.05'f32)
      )
    )
  result.add newMorph(nameJA = "wave", nameEN = "", morphType = mtVertex, offsetData = wave)
  result.add newMorph(
    nameJA = "wave group",
    nameEN = "",
    morphType = mtGroup,
    offsetData = @[
      MorphOffset(kind: moGroup, group: GroupMorphOffset(morphIndex: 0'i32, influence: 1.0'f32))
    ]
  )
  result.add newMorph(
    nameJA = "wave flip",
    nameEN = "",
    morphType = mtFlip,
    offsetData = @[MorphOffset(kind: moFlip, flip: FlipMorphOffset(morphIndex: 0'i32, influence: 0.5'f32))]
  )

proc makeDisplayFrames(): seq[DisplaySlot] =
  ## Groups the bones and the morphs the way MMD shows them.
  var boneFrames: seq[DisplayFrame] = @[]
  for index in 0 ..< Bones:
    boneFrames.add newBoneDisplayFrame(int32(index))
  var morphFrames: seq[DisplayFrame] = @[]
  for index in 0 .. 2:
    morphFrames.add newMorphDisplayFrame(int32(index))
  result.add newDisplaySlot(nameJA = "Root", nameEN = "", specialFlag = true, frames = boneFrames)
  result.add newDisplaySlot(nameJA = "Expressions", nameEN = "", frames = morphFrames)

proc makeModel*(): PmxModel =
  ## Assembles the mesh, the rig, and the physics into one document.
  let faces = makeFaces()
  let topMiddle = int32((Columns + 1) * Rows)
  result = newPmxModel(
    nameJA = "cloth plane",
    nameEN = "cloth plane",
    commentsEN = "Generated by examples/make_sample.nim.",
    version = pmx21,
    textEncoding = teUTF8,
    vertices = makeVertices(),
    faces = faces,
    textures = @[
      newTexture("textures\\cloth.png"),
      newTexture("textures/cloth.png")
    ],
    materials = @[
      newMaterial(
        nameJA = "cloth",
        nameEN = "",
        flags = MaterialFlags(bothFace: true, groundShadow: true, edge: true),
        edgeColor = RGBA.black,
        textureIndex = 1'i32,
        faceCount = int32(faces.len)
      )
    ],
    bones = makeBones(),
    morphs = makeMorphs(),
    displayFrames = makeDisplayFrames(),
    rigidBodies = @[
      newRigidBody(
        nameJA = "root body",
        nameEN = "",
        relatedBoneIndex = 0'i32,
        shape = rbsBox,
        shapeSize = Vector3(x: 0.5'f32, y: 0.5'f32, z: 0.05'f32),
        shapePosition = Vector3(x: 0.0'f32, y: 0.5'f32, z: 0.0'f32)
      ),
      newRigidBody(
        nameJA = "tip body",
        nameEN = "",
        relatedBoneIndex = 3'i32,
        groupId = 2'i32,
        shape = rbsSphere,
        shapeSize = Vector3(x: 0.05'f32, y: 0.0'f32, z: 0.0'f32),
        shapePosition = Vector3(x: 0.0'f32, y: 1.0'f32, z: 0.0'f32),
        mass = 0.5'f32,
        physicsMode = pmPhysics
      )
    ],
    joints = @[
      newJoint(
        nameJA = "tip joint",
        nameEN = "",
        rigidBodyIndexA = 0'i32,
        rigidBodyIndexB = 1'i32,
        jointType = jtPointToPoint,
        position = Vector3(x: 0.0'f32, y: 1.0'f32, z: 0.0'f32)
      )
    ],
    softBodies =
      @[
        newSoftBody(
          nameJA = "cloth",
          nameEN = "",
          materialIndex = 0'i32,
          flags = SoftBodyFlags(bLink: true, cluster: true),
          numberOfClusters = 2'i32,
          totalMass = 1.0'f32,
          anchorRigidBodies = @[AnchorRigidBody(rigidBodyIndex: 1'i32, vertexIndex: topMiddle)],
          vertexPins = @[0'i32, topMiddle]
        )
      ]
  )

when isMainModule:
  let outputPath = if paramCount() >= 1: paramStr(1) else: "sample.pmx"

  let model = makeModel()
  validate(model)
  writePmx(model, outputPath)

  echo fmt"wrote {outputPath} ({getFileSize(outputPath)} bytes)"
  echo fmt"{model.vertices.len} vertices, {model.faces.len} faces, {model.bones.len} bones"
  echo fmt"{model.morphs.len} morphs, {model.rigidBodies.len} rigid bodies, " &
    fmt"{model.softBodies.len} soft bodies"
  echo "needs PMX 2.1: ", isPmx21Only(model)
